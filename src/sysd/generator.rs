/// Runtime units are regenerated on every router start, then made visible with
/// one systemd manager reload.
pub const GENERATED_UNIT_DIRECTORY: &str = "/run/systemd/system";

#[derive(Debug, Error)]
pub enum GeneratedSystemdError {
    #[error(transparent)]
    InvalidConfiguration(#[from] ValidationErrors),
    #[error("cannot render systemd inputs for service {service:?}: {reason}")]
    Render { service: String, reason: String },
    #[error("multiple services would write generated systemd input {path}")]
    DuplicateOutput { path: PathBuf },
    #[error("cannot {operation} {path}: {source}")]
    Io {
        operation: &'static str,
        path: PathBuf,
        #[source]
        source: io::Error,
    },
}

struct RenderedService {
    unit_path: PathBuf,
    unit: String,
    environment_path: PathBuf,
    environment: String,
}

/// Render and atomically install all configured unit and environment files.
///
/// Files are completely rendered before the first write. Each destination is
/// replaced atomically in its own directory with its final restrictive mode.
/// The caller must reload the systemd manager after this returns successfully.
pub fn install_generated_inputs(
    config: &RouterConfig,
    gpu_indices: &BTreeMap<String, u32>,
) -> Result<(), GeneratedSystemdError> {
    install_generated_inputs_in(config, gpu_indices, Path::new(GENERATED_UNIT_DIRECTORY))
}

/// Render every generated input without writing anything to the host.
///
/// The only place a placement UUID meets the live NVML inventory is rendering,
/// so config-check mode runs the identical renderer to decide whether the units
/// this configuration would install can be produced at all.
pub fn dry_run_generated_inputs(
    config: &RouterConfig,
    gpu_indices: &BTreeMap<String, u32>,
) -> Result<(), GeneratedSystemdError> {
    render_all(config, gpu_indices, Path::new(GENERATED_UNIT_DIRECTORY)).map(|_| ())
}

fn install_generated_inputs_in(
    config: &RouterConfig,
    gpu_indices: &BTreeMap<String, u32>,
    unit_directory: &Path,
) -> Result<(), GeneratedSystemdError> {
    let rendered = render_all(config, gpu_indices, unit_directory)?;

    ensure_directory(unit_directory, 0o755)?;
    for service in rendered {
        ensure_parent_directory(&service.environment_path)?;
        atomic_write(
            &service.environment_path,
            service.environment.as_bytes(),
            0o600,
        )?;
        atomic_write(&service.unit_path, service.unit.as_bytes(), 0o644)?;
    }
    Ok(())
}

/// Render all services, completely, before any destination is touched.
fn render_all(
    config: &RouterConfig,
    gpu_indices: &BTreeMap<String, u32>,
    unit_directory: &Path,
) -> Result<Vec<RenderedService>, GeneratedSystemdError> {
    config.validate()?;

    let mut destinations = HashSet::new();
    config
        .services
        .iter()
        .map(|service| {
            let aliases = aliases_for_canonical_model(config, &service.served_model);
            let rendered = render_service_with_aliases(
                service,
                &aliases,
                &config.environment,
                gpu_indices,
                unit_directory,
            )?;
            for path in [&rendered.unit_path, &rendered.environment_path] {
                if !destinations.insert(path.clone()) {
                    return Err(GeneratedSystemdError::DuplicateOutput { path: path.clone() });
                }
            }
            Ok(rendered)
        })
        .collect()
}

#[cfg(test)]
fn render_service(
    service: &ServiceDefinition,
    global_environment: &BTreeMap<String, String>,
    gpu_indices: &BTreeMap<String, u32>,
    unit_directory: &Path,
) -> Result<RenderedService, GeneratedSystemdError> {
    render_service_with_aliases(
        service,
        &service.aliases,
        global_environment,
        gpu_indices,
        unit_directory,
    )
}

fn render_service_with_aliases(
    service: &ServiceDefinition,
    aliases: &[String],
    global_environment: &BTreeMap<String, String>,
    gpu_indices: &BTreeMap<String, u32>,
    unit_directory: &Path,
) -> Result<RenderedService, GeneratedSystemdError> {
    validate_unit_filename(service)?;
    let environment_path = service.systemd.environment_file.clone();
    let environment_path_text = path_text(service, &environment_path, "environment file")?;
    let sleep_enabled = service.sleep.enabled && service.sleep.hardware_validated;

    let mut environment = format!(
        "# Generated by vllm-router; local edits are overwritten.\n\
         CUDA_DEVICE_ORDER=PCI_BUS_ID\n\
         CUDA_VISIBLE_DEVICES={}\n",
        cuda_visible_devices(service, gpu_indices)?
    );
    let mut configured_environment = global_environment.clone();
    configured_environment.extend(service.environment.clone());
    for (name, value) in configured_environment {
        environment.push_str(&name);
        environment.push('=');
        environment.push_str(&environment_value(service, &value)?);
        environment.push('\n');
    }
    if sleep_enabled {
        environment.push_str("VLLM_SERVER_DEV_MODE=1\n");
    }

    let arguments = vllm_arguments(service, aliases, sleep_enabled)?;
    let command = arguments
        .iter()
        .map(|argument| exec_argument(service, argument))
        .collect::<Result<Vec<_>, _>>()?
        .join(" ");
    let executable_path = path_text(
        service,
        &service.runner_executable,
        "runner executable path",
    )?;
    let executable = exec_argument(service, executable_path)?;
    let environment_directive = environment_file_argument(service, environment_path_text)?;

    let unit = format!(
        "# Generated by vllm-router; local edits are overwritten.\n\
         [Unit]\n\
         Description=vLLM managed service ({name})\n\
         After=network-online.target\n\
         Wants=network-online.target\n\
         \n\
         [Service]\n\
         Type=simple\n\
         EnvironmentFile={environment_directive}\n\
         ExecStart=:{executable} {command}\n\
         Restart=on-failure\n\
         RestartSec={restart_ms}ms\n\
         TimeoutStartSec={startup_ms}ms\n\
         TimeoutStopSec={stop_ms}ms\n\
         KillSignal=SIGTERM\n\
         LimitMEMLOCK=infinity\n\
         LimitNOFILE=65535\n\
         NoNewPrivileges=true\n\
         PrivateTmp=true\n",
        name = service.name,
        restart_ms = service.retry.initial_backoff_ms,
        startup_ms = service.deadlines.startup_ms,
        stop_ms = service.deadlines.systemd_job_ms,
    );

    Ok(RenderedService {
        unit_path: unit_directory.join(&service.systemd.unit),
        unit,
        environment_path,
        environment,
    })
}

fn vllm_arguments(
    service: &ServiceDefinition,
    aliases: &[String],
    sleep_enabled: bool,
) -> Result<Vec<String>, GeneratedSystemdError> {
    let mut arguments = vec![
        "serve".into(),
        path_text(service, &service.model_path, "model path")?.into(),
        "--host".into(),
        service.backend.address.to_string(),
        "--port".into(),
        service.backend.port.to_string(),
        "--served-model-name".into(),
        service.served_model.clone(),
    ];
    arguments.extend(aliases.iter().cloned());
    arguments.extend([
        "--tensor-parallel-size".into(),
        service.placement.tensor_parallelism.to_string(),
        "--pipeline-parallel-size".into(),
        service.placement.pipeline_parallelism.to_string(),
        "--data-parallel-size".into(),
        service.placement.data_parallelism.to_string(),
        "--gpu-memory-utilization".into(),
        service.compatibility.gpu_memory_utilization.to_string(),
    ]);

    if let Some(path) = &service.tokenizer.path {
        arguments.push("--tokenizer".into());
        arguments.push(path_text(service, path, "tokenizer path")?.into());
    }
    if let Some(mode) = &service.tokenizer.mode {
        push_value_argument(&mut arguments, "tokenizer-mode", mode);
    }
    if let Some(revision) = &service.tokenizer.revision {
        if service.runner_args.contains_key("tokenizer-revision") {
            return render_error(
                service,
                "tokenizer revision is configured in both tokenizer.revision and runner_args",
            );
        }
        push_value_argument(&mut arguments, "tokenizer-revision", revision);
    }
    if service.tokenizer.trust_remote_code {
        arguments.push("--trust-remote-code".into());
    }
    if let Some(quantization) = &service.quantization {
        push_value_argument(&mut arguments, "quantization", quantization);
    }
    if let Some(maximum_model_length) = service.compatibility.maximum_model_length {
        push_value_argument(
            &mut arguments,
            "max-model-len",
            &maximum_model_length.to_string(),
        );
    }
    if let Some(kv_cache_dtype) = &service.compatibility.kv_cache_dtype {
        push_value_argument(&mut arguments, "kv-cache-dtype", kv_cache_dtype);
    }
    if sleep_enabled {
        arguments.push("--enable-sleep-mode".into());
    }
    if !service
        .runner_args
        .contains_key("distributed-executor-backend")
    {
        push_value_argument(&mut arguments, "distributed-executor-backend", "mp");
    }

    const PARSER_ARGUMENT_ORDER: &[&str] = &[
        "enable-auto-tool-choice",
        "tool-call-parser",
        "reasoning-parser",
    ];
    for (name, value) in &service.runner_args {
        if !PARSER_ARGUMENT_ORDER.contains(&name.as_str()) {
            push_runner_argument(&mut arguments, name, value);
        }
    }
    for name in PARSER_ARGUMENT_ORDER {
        if let Some(value) = service.runner_args.get(*name) {
            push_runner_argument(&mut arguments, name, value);
        }
    }
    Ok(arguments)
}

fn aliases_for_canonical_model(config: &RouterConfig, canonical: &str) -> Vec<String> {
    let mut seen = HashSet::new();
    let mut aliases = Vec::new();
    for service in &config.services {
        if service.served_model != canonical {
            continue;
        }
        for alias in &service.aliases {
            if seen.insert(alias.as_str()) {
                aliases.push(alias.clone());
            }
        }
    }
    aliases
}

fn push_value_argument(arguments: &mut Vec<String>, name: &str, value: &str) {
    arguments.push(format!("--{name}"));
    arguments.push(value.to_owned());
}

fn push_runner_argument(arguments: &mut Vec<String>, name: &str, value: &RunnerArgValue) {
    match value {
        RunnerArgValue::Bool(true) => arguments.push(format!("--{name}")),
        RunnerArgValue::Bool(false) => {}
        RunnerArgValue::Integer(value) => {
            push_value_argument(arguments, name, &value.to_string());
        }
        RunnerArgValue::Float(value) => {
            push_value_argument(arguments, name, &value.to_string());
        }
        RunnerArgValue::String(value) => {
            push_value_argument(arguments, name, value);
        }
    }
}

fn validate_unit_filename(service: &ServiceDefinition) -> Result<(), GeneratedSystemdError> {
    let unit = &service.systemd.unit;
    if unit.is_empty()
        || !unit.ends_with(".service")
        || !unit
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || b"@_.:-".contains(&byte))
    {
        return render_error(
            service,
            "systemd unit is not a safe literal .service filename",
        );
    }
    Ok(())
}

fn path_text<'a>(
    service: &ServiceDefinition,
    path: &'a Path,
    field: &str,
) -> Result<&'a str, GeneratedSystemdError> {
    path.to_str().ok_or_else(|| GeneratedSystemdError::Render {
        service: service.name.clone(),
        reason: format!("{field} is not valid UTF-8"),
    })
}

fn exec_argument(
    service: &ServiceDefinition,
    value: &str,
) -> Result<String, GeneratedSystemdError> {
    reject_control_characters(service, value, "command argument")?;
    let escaped = value
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('%', "%%");
    Ok(format!("\"{escaped}\""))
}

fn environment_file_argument(
    service: &ServiceDefinition,
    value: &str,
) -> Result<String, GeneratedSystemdError> {
    reject_control_characters(service, value, "unit directive argument")?;
    if !value.starts_with('/')
        || value
            .bytes()
            .any(|byte| byte.is_ascii_whitespace() || b"\\\"'%".contains(&byte))
    {
        return render_error(
            service,
            "environment file path is not safe for a bare EnvironmentFile= directive",
        );
    }
    Ok(value.to_owned())
}

fn environment_value(
    service: &ServiceDefinition,
    value: &str,
) -> Result<String, GeneratedSystemdError> {
    reject_control_characters(service, value, "environment value")?;
    let escaped = value
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('`', "\\`")
        .replace('$', "\\$");
    Ok(format!("\"{escaped}\""))
}

fn cuda_visible_devices(
    service: &ServiceDefinition,
    gpu_indices: &BTreeMap<String, u32>,
) -> Result<String, GeneratedSystemdError> {
    let mut indices = Vec::with_capacity(service.placement.gpu_uuids.len());
    for uuid in &service.placement.gpu_uuids {
        let Some(index) = gpu_indices.get(uuid) else {
            return render_error(
                service,
                format!("GPU UUID {uuid:?} was not found in the live NVML inventory"),
            );
        };
        indices.push(index.to_string());
    }
    environment_value(service, &indices.join(","))
}

fn reject_control_characters(
    service: &ServiceDefinition,
    value: &str,
    kind: &str,
) -> Result<(), GeneratedSystemdError> {
    if value.chars().any(char::is_control) {
        return render_error(service, format!("{kind} contains a control character"));
    }
    Ok(())
}

fn render_error<T>(
    service: &ServiceDefinition,
    reason: impl Into<String>,
) -> Result<T, GeneratedSystemdError> {
    Err(GeneratedSystemdError::Render {
        service: service.name.clone(),
        reason: reason.into(),
    })
}

fn ensure_parent_directory(path: &Path) -> Result<(), GeneratedSystemdError> {
    let parent = path.parent().ok_or_else(|| GeneratedSystemdError::Render {
        service: "<unknown>".into(),
        reason: format!("output path {path:?} has no parent directory"),
    })?;
    ensure_directory(parent, 0o750)
}

fn ensure_directory(path: &Path, mode: u32) -> Result<(), GeneratedSystemdError> {
    let mut builder = DirBuilder::new();
    builder.recursive(true).mode(mode);
    builder
        .create(path)
        .map_err(|source| GeneratedSystemdError::Io {
            operation: "create directory",
            path: path.to_path_buf(),
            source,
        })
}

fn atomic_write(path: &Path, contents: &[u8], mode: u32) -> Result<(), GeneratedSystemdError> {
    if let Ok(metadata) = fs::symlink_metadata(path) {
        if !metadata.file_type().is_file() {
            return Err(GeneratedSystemdError::Io {
                operation: "replace non-regular output",
                path: path.to_path_buf(),
                source: io::Error::new(
                    io::ErrorKind::InvalidInput,
                    "destination is not a regular file",
                ),
            });
        }
    }

    let parent = path.parent().ok_or_else(|| GeneratedSystemdError::Io {
        operation: "locate parent directory for",
        path: path.to_path_buf(),
        source: io::Error::new(io::ErrorKind::InvalidInput, "path has no parent"),
    })?;
    let filename = path.file_name().ok_or_else(|| GeneratedSystemdError::Io {
        operation: "locate filename for",
        path: path.to_path_buf(),
        source: io::Error::new(io::ErrorKind::InvalidInput, "path has no filename"),
    })?;
    let temporary_path = parent.join(format!(
        ".{}.tmp-{}",
        filename.to_string_lossy(),
        Uuid::new_v4()
    ));

    let result = write_and_replace(&temporary_path, path, contents, mode);
    if result.is_err() {
        let _ = fs::remove_file(&temporary_path);
    }
    result
}

fn write_and_replace(
    temporary_path: &Path,
    destination: &Path,
    contents: &[u8],
    mode: u32,
) -> Result<(), GeneratedSystemdError> {
    let mut temporary = OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .open(temporary_path)
        .map_err(|source| GeneratedSystemdError::Io {
            operation: "create temporary file",
            path: temporary_path.to_path_buf(),
            source,
        })?;
    temporary
        .write_all(contents)
        .and_then(|()| temporary.flush())
        .map_err(|source| GeneratedSystemdError::Io {
            operation: "write temporary file",
            path: temporary_path.to_path_buf(),
            source,
        })?;
    temporary
        .set_permissions(fs::Permissions::from_mode(mode))
        .and_then(|()| temporary.sync_all())
        .map_err(|source| GeneratedSystemdError::Io {
            operation: "sync temporary file",
            path: temporary_path.to_path_buf(),
            source,
        })?;
    fs::rename(temporary_path, destination).map_err(|source| GeneratedSystemdError::Io {
        operation: "atomically replace",
        path: destination.to_path_buf(),
        source,
    })?;
    File::open(
        destination
            .parent()
            .expect("destination parent checked before temporary file creation"),
    )
    .and_then(|directory| directory.sync_all())
    .map_err(|source| GeneratedSystemdError::Io {
        operation: "sync parent directory for",
        path: destination.to_path_buf(),
        source,
    })
}

